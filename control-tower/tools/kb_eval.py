"""
The Logistics Assessment: run ATLAS's Knowledge Engine over the evaluation
set and report how it actually did.

    python tools/kb_eval.py                    # knowledge/eval/eval_v1.json
    python tools/kb_eval.py --write-report     # also knowledge/eval/REPORT.md

Each case is scored on what can be checked without a person:
    retrieval    an expected item is among the items the answer used
    content      every must_include phrase is there, no must_not_include
    value        a calculation's result equals expect_value
    declined     expect_none: the engine gave no answer
    attribution  an answer carries its knowledge status line, and its
                 sources when the item cites any
A case passes when every check that applies to it passes. Reasoning quality
beyond these checks is not measured here; the report says so.
"""
import argparse
import json
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from intelligence import kb as KB  # noqa: E402
from intelligence import kb_answer as A  # noqa: E402


def score(case):
    t0 = time.perf_counter()
    r = A.answer(case["question"])
    ms = (time.perf_counter() - t0) * 1000
    checks = {}
    text = (r or {}).get("answer", "") or ""
    low = text.lower()
    used = ((r or {}).get("knowledge") or {}).get("items") or []
    if case.get("expect_none"):
        checks["declined"] = r is None
    else:
        if r is None:
            checks["answered"] = False
        if case.get("expect_items"):
            checks["retrieval"] = any(i in used for i in case["expect_items"])
        if case.get("must_include"):
            checks["content"] = all(p.lower() in low for p in case["must_include"])
        if case.get("must_not_include"):
            checks["no_forbidden"] = not any(p.lower() in low for p in case["must_not_include"])
        if "expect_value" in case:
            calc = ((r or {}).get("knowledge") or {}).get("calculation") or {}
            checks["value"] = calc.get("value") is not None and abs(float(calc["value"]) - float(case["expect_value"])) < 1e-6
        if r is not None and used:
            k = KB.kb()
            cites = any(k.cite(k.get(i)) for i in used if k.get(i))
            checks["attribution"] = "_Knowledge status" in text and ("**Sources**" in text or not cites)
    ok = all(checks.values()) if checks else r is not None
    return {"id": case["id"], "type": case["type"], "question": case["question"], "ok": ok,
            "checks": checks, "used": used, "ms": round(ms, 1),
            "mode": ((r or {}).get("knowledge") or {}).get("mode")}


def run(path=None):
    path = Path(path or ROOT / "knowledge" / "eval" / "eval_v1.json")
    data = json.loads(path.read_text(encoding="utf-8"))
    results = [score(c) for c in data["cases"]]
    by = {}
    for r in results:
        t = by.setdefault(r["type"], [0, 0])
        t[0] += r["ok"]
        t[1] += 1
    k = KB.kb()
    return {"set": path.name, "version": data.get("version"), "cases": len(results),
            "passed": sum(r["ok"] for r in results), "by_type": by, "results": results,
            "kb": k.stats(), "median_ms": sorted(r["ms"] for r in results)[len(results) // 2]}


def report_md(rep):
    lines = ["# Logistics Assessment report", "",
             "Generated by `python tools/kb_eval.py --write-report` on {0}, set `{1}` v{2}.".format(
                 time.strftime("%Y-%m-%d"), rep["set"], rep["version"]), "",
             "**{0} of {1} cases passed ({2:.0f}%).** Median answer time {3} ms on the build machine.".format(
                 rep["passed"], rep["cases"], 100.0 * rep["passed"] / rep["cases"], rep["median_ms"]), "",
             "| Type | Passed |", "|---|---|"]
    for t, (ok, n) in sorted(rep["by_type"].items()):
        lines.append("| {0} | {1} / {2} |".format(t, ok, n))
    fails = [r for r in rep["results"] if not r["ok"]]
    lines += ["", "## Cases that failed", ""]
    if not fails:
        lines.append("None.")
    for r in fails:
        bad = ", ".join(k for k, v in r["checks"].items() if not v) or "no answer"
        lines.append("- `{0}` ({1}) — {2!r}: failed {3}; used {4}".format(r["id"], r["type"], r["question"], bad,
                                                                         r["used"] or "nothing"))
    s = rep["kb"]
    lines += ["", "## The knowledge it was measured on", "",
              "{0} items; review status {1}; evidence {2}.".format(s["items"], s["by_review"], s["by_evidence"]), "",
              "## What this does and does not show", "",
              "- It checks retrieval, required and forbidden content, exact calculations, declining out-of-scope "
              "and run questions, and that answers carry their status and sources.",
              "- **This score is optimistic.** The set was written alongside the engine and used to find its gaps "
              "(several were fixed because of it), so it is in-sample. The real measure is a held-out set written by "
              "Mantrac's logistics staff, in their own words; add it as eval_v2.json and run it unchanged.",
              "- It does not grade free-form reasoning: ATLAS's knowledge answers are composed from the knowledge "
              "items' text and deterministic calculations, not generated, so a pass means the right knowledge was "
              "found and stated — not that ATLAS 'understands' logistics like an expert.",
              "- Retrieval is keyword-based (BM25 with synonyms and Arabic folding). There is no embedding model in "
              "this platform; questions worded far from an item's words can miss it.",
              "- No item is yet approved by a Mantrac reviewer; answers say so.", ""]
    return "\n".join(lines)


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--set")
    ap.add_argument("--write-report", action="store_true")
    ap.add_argument("--json", action="store_true")
    a = ap.parse_args(argv)
    rep = run(a.set)
    if a.json:
        print(json.dumps(rep, indent=1, default=str))
    else:
        for r in rep["results"]:
            print("{0} {1:8} {2:15} {3}".format("PASS" if r["ok"] else "FAIL", r["id"], r["type"],
                                                "" if r["ok"] else {k: v for k, v in r["checks"].items() if not v}))
        print("\n{0} of {1} passed".format(rep["passed"], rep["cases"]))
    if a.write_report:
        (ROOT / "knowledge" / "eval" / "REPORT.md").write_text(report_md(rep), encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
