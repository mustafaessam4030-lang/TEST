-- Service Intelligence — Phase 1: database, schemas and copies of CAT_SHARE tables
-- Account FY56654 (AZURE_WESTEUROPE). Run in Snowsight as a role that can CREATE DATABASE
-- (e.g. DEV_ADMIN or SYSADMIN) and read CAT_SHARE (imported share, owner ACCOUNTADMIN).
--
-- Phase 1 scope (not final; add tables to the same pattern later):
--   CAT_SHARE.DOMAIN_TELEMETRY : FAULT_CODE_BASIC_DAILY, FAULT_CODE_HISTORY,
--                                TELEMETRY_FUEL_BASIC_DAILY, TELEMETRY_SMU_LOCATION_BASIC_DAILY
--   CAT_SHARE.OLGA             : COMPANY_CONFIG_TABLE, CUSTOMER_TOTALS_TABLE,
--                                EQUIPMENT_REPORT_DETAIL_TABLE, LOST_OPPORTUNITY_REPORT_TABLE,
--                                OPPORTUNITIES_TABLE, OPPORTUNITY_MAJORCLASS_SUBCATEGORY_PARTCOST_TABLE
--
-- Size (SHOW TABLES, 23 Oct 2026): ~407M rows, ~15.8 GB compressed in total. The largest are
-- OPPORTUNITY_MAJORCLASS_SUBCATEGORY_PARTCOST_TABLE (245M rows, 3.6 GB) and
-- FAULT_CODE_BASIC_DAILY (68M rows, 4.2 GB).
--
-- Notes
--  * Shared tables cannot be CLONEd, so this copies with CREATE TABLE ... AS SELECT.
--  * Normal (permanent) schemas and tables: Time Travel (1 day here) plus 7 days of Fail-safe, billed as storage.
--  * A copy is a SNAPSHOT. CAT_SHARE keeps updating; re-run section 3 to refresh.
--  * Check that Caterpillar's data-share terms allow copies before using them outside the dealer.
-- =====================================================================================

-- 1. Context. X-Small works but the two largest copies are slow on it; DEVELOPMENT_WH is shared,
--    so only resize it if nobody else needs it (and revert in section 5).
USE ROLE DEV_ADMIN;
USE WAREHOUSE DEVELOPMENT_WH;
-- ALTER WAREHOUSE DEVELOPMENT_WH SET WAREHOUSE_SIZE = 'MEDIUM';

-- 2. Database and schemas (schemas mirror the source schemas, for lineage).
CREATE DATABASE IF NOT EXISTS SERVICE_INTELLIGENCE
  DATA_RETENTION_TIME_IN_DAYS = 1   -- raise for longer Time Travel (more storage cost)
  COMMENT = 'Service Intelligence project. Phase 1: copies of CAT_SHARE DOMAIN_TELEMETRY and OLGA tables.';
CREATE SCHEMA IF NOT EXISTS SERVICE_INTELLIGENCE.DOMAIN_TELEMETRY
  COMMENT = 'Copy of CAT_SHARE.DOMAIN_TELEMETRY (Cat telemetry: fault codes, fuel, SMU/location)';
CREATE SCHEMA IF NOT EXISTS SERVICE_INTELLIGENCE.OLGA
  COMMENT = 'Copy of CAT_SHARE.OLGA (Cat OLGA opportunities / lost opportunity reports)';
CREATE SCHEMA IF NOT EXISTS SERVICE_INTELLIGENCE.SI_ADMIN
  COMMENT = 'Service Intelligence load log and application state';

CREATE TABLE IF NOT EXISTS SERVICE_INTELLIGENCE.SI_ADMIN.COPY_LOG (
  copied_at     TIMESTAMP_LTZ DEFAULT CURRENT_TIMESTAMP(),
  source_table  VARCHAR,
  target_table  VARCHAR,
  source_rows   NUMBER,
  target_rows   NUMBER
);

-- 3. Copies (re-runnable: CREATE OR REPLACE gives a fresh snapshot).
CREATE OR REPLACE TABLE SERVICE_INTELLIGENCE.DOMAIN_TELEMETRY.FAULT_CODE_BASIC_DAILY
  AS SELECT * FROM CAT_SHARE.DOMAIN_TELEMETRY.FAULT_CODE_BASIC_DAILY;
CREATE OR REPLACE TABLE SERVICE_INTELLIGENCE.DOMAIN_TELEMETRY.FAULT_CODE_HISTORY
  AS SELECT * FROM CAT_SHARE.DOMAIN_TELEMETRY.FAULT_CODE_HISTORY;
CREATE OR REPLACE TABLE SERVICE_INTELLIGENCE.DOMAIN_TELEMETRY.TELEMETRY_FUEL_BASIC_DAILY
  AS SELECT * FROM CAT_SHARE.DOMAIN_TELEMETRY.TELEMETRY_FUEL_BASIC_DAILY;
CREATE OR REPLACE TABLE SERVICE_INTELLIGENCE.DOMAIN_TELEMETRY.TELEMETRY_SMU_LOCATION_BASIC_DAILY
  AS SELECT * FROM CAT_SHARE.DOMAIN_TELEMETRY.TELEMETRY_SMU_LOCATION_BASIC_DAILY;

CREATE OR REPLACE TABLE SERVICE_INTELLIGENCE.OLGA.COMPANY_CONFIG_TABLE
  AS SELECT * FROM CAT_SHARE.OLGA.COMPANY_CONFIG_TABLE;
CREATE OR REPLACE TABLE SERVICE_INTELLIGENCE.OLGA.CUSTOMER_TOTALS_TABLE
  AS SELECT * FROM CAT_SHARE.OLGA.CUSTOMER_TOTALS_TABLE;
CREATE OR REPLACE TABLE SERVICE_INTELLIGENCE.OLGA.EQUIPMENT_REPORT_DETAIL_TABLE
  AS SELECT * FROM CAT_SHARE.OLGA.EQUIPMENT_REPORT_DETAIL_TABLE;
CREATE OR REPLACE TABLE SERVICE_INTELLIGENCE.OLGA.LOST_OPPORTUNITY_REPORT_TABLE
  AS SELECT * FROM CAT_SHARE.OLGA.LOST_OPPORTUNITY_REPORT_TABLE;
CREATE OR REPLACE TABLE SERVICE_INTELLIGENCE.OLGA.OPPORTUNITIES_TABLE
  AS SELECT * FROM CAT_SHARE.OLGA.OPPORTUNITIES_TABLE;
CREATE OR REPLACE TABLE SERVICE_INTELLIGENCE.OLGA.OPPORTUNITY_MAJORCLASS_SUBCATEGORY_PARTCOST_TABLE
  AS SELECT * FROM CAT_SHARE.OLGA.OPPORTUNITY_MAJORCLASS_SUBCATEGORY_PARTCOST_TABLE;

-- 4. Verify: row counts must match the source (expect 10 rows, all MATCH), and log them.
INSERT INTO SERVICE_INTELLIGENCE.SI_ADMIN.COPY_LOG (source_table, target_table, source_rows, target_rows)
WITH pairs AS (
  SELECT 'CAT_SHARE.DOMAIN_TELEMETRY.FAULT_CODE_BASIC_DAILY' s, (SELECT COUNT(*) FROM CAT_SHARE.DOMAIN_TELEMETRY.FAULT_CODE_BASIC_DAILY) sn,
         'SERVICE_INTELLIGENCE.DOMAIN_TELEMETRY.FAULT_CODE_BASIC_DAILY' t, (SELECT COUNT(*) FROM SERVICE_INTELLIGENCE.DOMAIN_TELEMETRY.FAULT_CODE_BASIC_DAILY) tn
  UNION ALL SELECT 'CAT_SHARE.DOMAIN_TELEMETRY.FAULT_CODE_HISTORY', (SELECT COUNT(*) FROM CAT_SHARE.DOMAIN_TELEMETRY.FAULT_CODE_HISTORY),
         'SERVICE_INTELLIGENCE.DOMAIN_TELEMETRY.FAULT_CODE_HISTORY', (SELECT COUNT(*) FROM SERVICE_INTELLIGENCE.DOMAIN_TELEMETRY.FAULT_CODE_HISTORY)
  UNION ALL SELECT 'CAT_SHARE.DOMAIN_TELEMETRY.TELEMETRY_FUEL_BASIC_DAILY', (SELECT COUNT(*) FROM CAT_SHARE.DOMAIN_TELEMETRY.TELEMETRY_FUEL_BASIC_DAILY),
         'SERVICE_INTELLIGENCE.DOMAIN_TELEMETRY.TELEMETRY_FUEL_BASIC_DAILY', (SELECT COUNT(*) FROM SERVICE_INTELLIGENCE.DOMAIN_TELEMETRY.TELEMETRY_FUEL_BASIC_DAILY)
  UNION ALL SELECT 'CAT_SHARE.DOMAIN_TELEMETRY.TELEMETRY_SMU_LOCATION_BASIC_DAILY', (SELECT COUNT(*) FROM CAT_SHARE.DOMAIN_TELEMETRY.TELEMETRY_SMU_LOCATION_BASIC_DAILY),
         'SERVICE_INTELLIGENCE.DOMAIN_TELEMETRY.TELEMETRY_SMU_LOCATION_BASIC_DAILY', (SELECT COUNT(*) FROM SERVICE_INTELLIGENCE.DOMAIN_TELEMETRY.TELEMETRY_SMU_LOCATION_BASIC_DAILY)
  UNION ALL SELECT 'CAT_SHARE.OLGA.COMPANY_CONFIG_TABLE', (SELECT COUNT(*) FROM CAT_SHARE.OLGA.COMPANY_CONFIG_TABLE),
         'SERVICE_INTELLIGENCE.OLGA.COMPANY_CONFIG_TABLE', (SELECT COUNT(*) FROM SERVICE_INTELLIGENCE.OLGA.COMPANY_CONFIG_TABLE)
  UNION ALL SELECT 'CAT_SHARE.OLGA.CUSTOMER_TOTALS_TABLE', (SELECT COUNT(*) FROM CAT_SHARE.OLGA.CUSTOMER_TOTALS_TABLE),
         'SERVICE_INTELLIGENCE.OLGA.CUSTOMER_TOTALS_TABLE', (SELECT COUNT(*) FROM SERVICE_INTELLIGENCE.OLGA.CUSTOMER_TOTALS_TABLE)
  UNION ALL SELECT 'CAT_SHARE.OLGA.EQUIPMENT_REPORT_DETAIL_TABLE', (SELECT COUNT(*) FROM CAT_SHARE.OLGA.EQUIPMENT_REPORT_DETAIL_TABLE),
         'SERVICE_INTELLIGENCE.OLGA.EQUIPMENT_REPORT_DETAIL_TABLE', (SELECT COUNT(*) FROM SERVICE_INTELLIGENCE.OLGA.EQUIPMENT_REPORT_DETAIL_TABLE)
  UNION ALL SELECT 'CAT_SHARE.OLGA.LOST_OPPORTUNITY_REPORT_TABLE', (SELECT COUNT(*) FROM CAT_SHARE.OLGA.LOST_OPPORTUNITY_REPORT_TABLE),
         'SERVICE_INTELLIGENCE.OLGA.LOST_OPPORTUNITY_REPORT_TABLE', (SELECT COUNT(*) FROM SERVICE_INTELLIGENCE.OLGA.LOST_OPPORTUNITY_REPORT_TABLE)
  UNION ALL SELECT 'CAT_SHARE.OLGA.OPPORTUNITIES_TABLE', (SELECT COUNT(*) FROM CAT_SHARE.OLGA.OPPORTUNITIES_TABLE),
         'SERVICE_INTELLIGENCE.OLGA.OPPORTUNITIES_TABLE', (SELECT COUNT(*) FROM SERVICE_INTELLIGENCE.OLGA.OPPORTUNITIES_TABLE)
  UNION ALL SELECT 'CAT_SHARE.OLGA.OPPORTUNITY_MAJORCLASS_SUBCATEGORY_PARTCOST_TABLE', (SELECT COUNT(*) FROM CAT_SHARE.OLGA.OPPORTUNITY_MAJORCLASS_SUBCATEGORY_PARTCOST_TABLE),
         'SERVICE_INTELLIGENCE.OLGA.OPPORTUNITY_MAJORCLASS_SUBCATEGORY_PARTCOST_TABLE', (SELECT COUNT(*) FROM SERVICE_INTELLIGENCE.OLGA.OPPORTUNITY_MAJORCLASS_SUBCATEGORY_PARTCOST_TABLE)
)
SELECT s, t, sn, tn FROM pairs;

SELECT source_table, target_table, source_rows, target_rows,
       IFF(source_rows = target_rows, 'MATCH', 'MISMATCH') AS check_result
FROM SERVICE_INTELLIGENCE.SI_ADMIN.COPY_LOG
QUALIFY ROW_NUMBER() OVER (PARTITION BY target_table ORDER BY copied_at DESC) = 1
ORDER BY target_table;

