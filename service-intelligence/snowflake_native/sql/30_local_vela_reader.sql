-- The user the laptop signs in with (key-pair only, no password)
CREATE USER IF NOT EXISTS VELA_LOCAL
    TYPE = SERVICE
    DEFAULT_ROLE = VELA_LOCAL_READER
    DEFAULT_WAREHOUSE = SI_WH
    COMMENT = 'VELA AI local app (Ollama on a laptop), read-only';
ALTER USER VELA_LOCAL SET RSA_PUBLIC_KEY = '<paste the public key printed by local/make_key.py>';
GRANT ROLE VELA_LOCAL_READER TO USER VELA_LOCAL;

