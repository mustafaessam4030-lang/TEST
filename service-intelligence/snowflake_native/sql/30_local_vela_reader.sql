-- =====================================================================================
-- VELA AI local (Ollama on a laptop): a READ-ONLY Snowflake role and user for the local app
-- Run in a Snowsight SQL worksheet as ACCOUNTADMIN. Re-runnable. Grants SELECT/USAGE/READ only:
-- the local app can read the data and use the search services, it cannot change anything.
--
-- Before running: on the laptop run  python local/make_key.py  and paste the printed public key below.
-- =====================================================================================
USE ROLE ACCOUNTADMIN;

CREATE ROLE IF NOT EXISTS VELA_LOCAL_READER COMMENT = 'VELA AI local app: read-only data, Cortex Search and Cortex AI functions';

-- Compute and Cortex
GRANT USAGE ON WAREHOUSE SI_WH TO ROLE VELA_LOCAL_READER;
GRANT DATABASE ROLE SNOWFLAKE.CORTEX_USER TO ROLE VELA_LOCAL_READER;      -- Cortex Search, web search, AI functions

-- Database and schemas
GRANT USAGE ON DATABASE SERVICE_INTELLIGENCE TO ROLE VELA_LOCAL_READER;
GRANT USAGE ON SCHEMA SERVICE_INTELLIGENCE.CURATED TO ROLE VELA_LOCAL_READER;
GRANT USAGE ON SCHEMA SERVICE_INTELLIGENCE.SI_APP  TO ROLE VELA_LOCAL_READER;
GRANT USAGE ON SCHEMA SERVICE_INTELLIGENCE.AI_BRAIN TO ROLE VELA_LOCAL_READER;

-- Fleet data (curated layer) and the app's read tables
GRANT SELECT ON ALL TABLES IN SCHEMA SERVICE_INTELLIGENCE.CURATED TO ROLE VELA_LOCAL_READER;
GRANT SELECT ON ALL VIEWS  IN SCHEMA SERVICE_INTELLIGENCE.CURATED TO ROLE VELA_LOCAL_READER;
GRANT SELECT ON TABLE SERVICE_INTELLIGENCE.SI_APP.DAILY_TOP_OPPORTUNITIES TO ROLE VELA_LOCAL_READER;
GRANT SELECT ON TABLE SERVICE_INTELLIGENCE.SI_APP.APP_USERS              TO ROLE VELA_LOCAL_READER;
GRANT SELECT ON TABLE SERVICE_INTELLIGENCE.SI_APP.RECOMMENDATIONS        TO ROLE VELA_LOCAL_READER;
GRANT SELECT ON TABLE SERVICE_INTELLIGENCE.SI_APP.RECOMMENDATION_EVENTS  TO ROLE VELA_LOCAL_READER;

-- AI Brain: the reference tables VELA reads (logs, caches and photo uploads are NOT granted)
GRANT SELECT ON TABLE SERVICE_INTELLIGENCE.AI_BRAIN.MACHINE_FLEET      TO ROLE VELA_LOCAL_READER;
GRANT SELECT ON TABLE SERVICE_INTELLIGENCE.AI_BRAIN.REPAIR_KNOWLEDGE   TO ROLE VELA_LOCAL_READER;
GRANT SELECT ON TABLE SERVICE_INTELLIGENCE.AI_BRAIN.CVA_MACHINE        TO ROLE VELA_LOCAL_READER;
GRANT SELECT ON TABLE SERVICE_INTELLIGENCE.AI_BRAIN.CUSTOMER_SAT       TO ROLE VELA_LOCAL_READER;
GRANT SELECT ON TABLE SERVICE_INTELLIGENCE.AI_BRAIN.BRAIN_RULES        TO ROLE VELA_LOCAL_READER;
GRANT SELECT ON TABLE SERVICE_INTELLIGENCE.AI_BRAIN.TERRITORY_POLICY   TO ROLE VELA_LOCAL_READER;
GRANT SELECT ON TABLE SERVICE_INTELLIGENCE.AI_BRAIN.SOURCE_HEALTH      TO ROLE VELA_LOCAL_READER;
GRANT SELECT ON VIEW  SERVICE_INTELLIGENCE.AI_BRAIN.V_MACHINE_360      TO ROLE VELA_LOCAL_READER;
GRANT SELECT ON VIEW  SERVICE_INTELLIGENCE.AI_BRAIN.V_SERVICE_JOBS     TO ROLE VELA_LOCAL_READER;
GRANT SELECT ON VIEW  SERVICE_INTELLIGENCE.AI_BRAIN.V_SOS              TO ROLE VELA_LOCAL_READER;
GRANT SELECT ON VIEW  SERVICE_INTELLIGENCE.AI_BRAIN.V_INSPECTIONS      TO ROLE VELA_LOCAL_READER;
GRANT SELECT ON VIEW  SERVICE_INTELLIGENCE.AI_BRAIN.V_SERVICE_LETTERS  TO ROLE VELA_LOCAL_READER;
GRANT SELECT ON VIEW  SERVICE_INTELLIGENCE.AI_BRAIN.V_CAT_ALERTS       TO ROLE VELA_LOCAL_READER;
GRANT SELECT ON VIEW  SERVICE_INTELLIGENCE.AI_BRAIN.V_SMU_LATEST       TO ROLE VELA_LOCAL_READER;
GRANT SELECT ON VIEW  SERVICE_INTELLIGENCE.AI_BRAIN.V_SMU_READINGS_ALLOWED TO ROLE VELA_LOCAL_READER;
GRANT SELECT ON VIEW  SERVICE_INTELLIGENCE.AI_BRAIN.V_CVA_ENROLMENT    TO ROLE VELA_LOCAL_READER;
GRANT SELECT ON VIEW  SERVICE_INTELLIGENCE.AI_BRAIN.V_CUST_CASES       TO ROLE VELA_LOCAL_READER;
GRANT SELECT ON VIEW  SERVICE_INTELLIGENCE.AI_BRAIN.V_CUST_SURVEY      TO ROLE VELA_LOCAL_READER;
GRANT SELECT ON VIEW  SERVICE_INTELLIGENCE.AI_BRAIN.V_FAULT_CODES      TO ROLE VELA_LOCAL_READER;   -- machine profile only

-- Training library: search service and the files behind it (manual pages, diagrams, videos)
GRANT USAGE ON CORTEX SEARCH SERVICE SERVICE_INTELLIGENCE.AI_BRAIN.TRAINING_KB_SEARCH TO ROLE VELA_LOCAL_READER;
GRANT READ ON STAGE SERVICE_INTELLIGENCE.AI_BRAIN.TRAINING_STG TO ROLE VELA_LOCAL_READER;

