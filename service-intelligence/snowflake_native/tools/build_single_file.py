"""Build dist/streamlit_app.py: the whole app in ONE file, for pasting into the Snowsight Streamlit editor
(no stage uploads, no extra packages). Run:  python tools/build_single_file.py
The multi-file app in app/ stays the source; never edit the generated file by hand."""
import json
from datetime import date
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
APP = ROOT / "app"
MODULES = ["metrics", "data", "analysis", "recommend", "plans", "assistant", "agent", "theme", "ui"]   # dependency order
PAGES = [("Analysis", "streamlit_app.py"), ("Recommendations", "pages/2_Recommendations.py"),
         ("Assistant", "pages/3_Assistant.py")]


def _plain(o):
    if isinstance(o, dict):
        return {k: _plain(v) for k, v in o.items()}
    if isinstance(o, list):
        return [_plain(v) for v in o]
    return o.isoformat() if isinstance(o, date) else o


def build() -> str:
    registry = _plain(yaml.safe_load((APP / "metrics.yaml").read_text(encoding="utf-8")))
    modules = {f"si_native.{m}": (APP / "si_native" / f"{m}.py").read_text(encoding="utf-8") for m in MODULES}
    pages = {name: (APP / path).read_text(encoding="utf-8") for name, path in PAGES}
    logo = (APP / "assets" / "mantrac_logo.svg").read_text(encoding="utf-8")
    return f'''# Service Intelligence: SINGLE-FILE BUILD for Streamlit in Snowflake.
# Generated by snowflake_native/tools/build_single_file.py from snowflake_native/app/ (registry {registry.get("version")}).
# Do not edit by hand: change app/ and rebuild. Paste this whole file into the Snowsight Streamlit editor.
import json
import sys
import types

import streamlit as st

st.set_page_config(page_title="Service Intelligence", page_icon="◆", layout="wide")

REGISTRY = json.loads({json.dumps(json.dumps(registry))})
MODULE_SOURCES = {json.dumps(modules, indent=0)}
PAGE_SOURCES = {json.dumps(pages, indent=0)}
LOGO_SVG = {json.dumps(logo)}


def install():
    """Register the embedded si_native package once per process."""
    pkg = sys.modules.get("si_native")
    if pkg is not None and getattr(pkg, "SINGLE_FILE", False):
        return
    pkg = types.ModuleType("si_native")
    pkg.__path__ = []
    pkg.SINGLE_FILE = True
    pkg.EMBEDDED_REGISTRY = REGISTRY
    pkg.EMBEDDED_LOGO = LOGO_SVG
    sys.modules["si_native"] = pkg
    for name, src in MODULE_SOURCES.items():
        short = name.split(".")[1]
        mod = types.ModuleType(name)
        mod.__package__ = "si_native"
        mod.__file__ = f"si_native/{{short}}.py"
        sys.modules[name] = mod
        exec(compile(src, mod.__file__, "exec"), mod.__dict__)
        setattr(pkg, short, mod)


def render():
    sys.modules["si_native.ui"].chrome()              # design + logo before the menu
    page = st.sidebar.radio("Menu", list(PAGE_SOURCES), key="si_page")
    exec(compile(PAGE_SOURCES[page], f"pages/{{page}}.py", "exec"), {{"__name__": "__main__"}})


install()
if __name__ == "__main__":
    render()
'''


if __name__ == "__main__":
    out = ROOT / "dist" / "streamlit_app.py"
    out.write_text(build(), encoding="utf-8")
    print(f"wrote {out} ({out.stat().st_size:,} bytes)")
